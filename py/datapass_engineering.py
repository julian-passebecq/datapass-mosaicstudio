"""Validate `datapass.engineering/1` sidecar records and write `datapass-c14n/1` canonical JSON. Standard library only.

Mirror of src/framework/engineering/contract.ts, which stays the source of truth: same rules, same fixed order, same
stable DP-ENG-nnn codes and the same `where` (JSON pointer) for every refusal, and byte-identical canonical JSON, so
both languages report the same digests. tests/fixtures/engineering (generated by scripts/make-engineering-corpus.mjs)
pins every decision for both.

`datapass-c14n/1` is RFC 8785 JCS: object keys sorted by UTF-16 code units, UTF-8 output, numbers written as
ECMAScript Number-to-String writes them (Python's float repr differs: 1.0 -> "1", 1e21 -> "1e+21", 1e-07 -> "1e-7"),
-0 written 0, NaN/Infinity, lone surrogates and non-JSON values refused (DP-ENG-016). Python ints are read as the
IEEE-754 double JSON.parse would give.

An approval-request is presentation only: no module here issues, stores or checks an approval. A viewToken is not an
authorization token.

Command line:
    python py/datapass_engineering.py validate FILE...   one JSON decision per file; exit 1 when any is refused
    python py/datapass_engineering.py c14n FILE           canonical bytes of one JSON file on stdout
"""
from __future__ import annotations

import hashlib
import json
import math
import re
import sys
from datetime import datetime, timezone
from typing import Any

FORMAT = "datapass.engineering"
VERSION = 1
CONTRACT = "datapass.engineering/1"
C14N = "datapass-c14n/1"
KINDS = ("artifact-ref", "run-receipt", "selection-binding", "approval-request", "parameter-diff")
RUN_STATUSES = ("queued", "running", "succeeded", "failed", "cancelled")
BINDING_STATUSES = ("sourced", "inferred", "unmapped")
LIMITS = {"textBytes": 1048576, "depth": 32, "list": 1000, "checks": 200, "artifacts": 200, "diagnostics": 200,
          "bindings": 500, "consumedBy": 100}
APPROVAL_STATE_KEYS = ("approval", "approvalStatus", "approval_status", "approved", "approvedAt", "approvedBy",
                       "authorization", "decidedAt", "decision", "grant", "granted", "signature", "status", "token")

# rule -> (code, gate); mirrors ENGINEERING_CODES in src/framework/engineering/contract.ts.
ENGINEERING_CODES = {
    "engineering-envelope": ("DP-ENG-001", "envelope"),
    "format": ("DP-ENG-002", "envelope"),
    "version": ("DP-ENG-003", "envelope"),
    "kind": ("DP-ENG-004", "envelope"),
    "unknown-key": ("DP-ENG-005", "structure"),
    "missing-key": ("DP-ENG-006", "structure"),
    "field-invalid": ("DP-ENG-007", "structure"),
    "digest": ("DP-ENG-008", "structure"),
    "duplicate-id": ("DP-ENG-009", "semantic"),
    "run-status": ("DP-ENG-010", "semantic"),
    "model-resolution": ("DP-ENG-011", "semantic"),
    "disjoint-lists": ("DP-ENG-012", "semantic"),
    "binding-status": ("DP-ENG-013", "semantic"),
    "approval-state": ("DP-ENG-014", "semantic"),
    "diff-change": ("DP-ENG-015", "semantic"),
    "c14n-value": ("DP-ENG-016", "c14n"),
}


class EngineeringError(ValueError):
    def __init__(self, rule: str, where: str, message: str):
        super().__init__((where or "/") + ": " + message)
        self.rule = rule
        self.code, self.gate = ENGINEERING_CODES[rule]
        self.where = where


def _fail(rule: str, where: str, message: str):
    raise EngineeringError(rule, where, message)


def _utf16_key(key: str) -> bytes:
    return key.encode("utf-16-be", "surrogatepass")


def _lone_surrogate(s: str) -> bool:
    try:
        s.encode("utf-8")
        return False
    except UnicodeEncodeError:
        return True


def _pointer(key: str) -> str:
    return key.replace("~", "~0").replace("/", "~1")


# ------------------------------------------------------------------------------------------------------------- c14n
def es_number(value: float) -> str:
    """ECMAScript Number::toString for a finite double (shortest round-trip digits, ES exponent rules)."""
    if value == 0:
        return "0"
    if value < 0:
        return "-" + es_number(-value)
    mantissa, _, exp = repr(value).partition("e")
    whole, _, frac = mantissa.partition(".")
    digits = whole + frac
    n = len(whole) + (int(exp) if exp else 0)
    stripped = digits.lstrip("0")
    n -= len(digits) - len(stripped)
    digits = stripped.rstrip("0")
    k = len(digits)
    if k <= n <= 21:
        return digits + "0" * (n - k)
    if 0 < n <= 21:
        return digits[:n] + "." + digits[n:]
    if -6 < n <= 0:
        return "0." + "0" * (-n) + digits
    e = n - 1
    sign = "+" if e >= 0 else "-"
    head = digits[0] + ("." + digits[1:] if k > 1 else "")
    return head + "e" + sign + str(abs(e))


def _c14n_string(s: str, where: str) -> str:
    if _lone_surrogate(s):
        _fail("c14n-value", where, "a string holds a lone surrogate")
    out = ['"']
    for ch in s:
        c = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif c < 0x20:
            out.append({8: "\\b", 9: "\\t", 10: "\\n", 12: "\\f", 13: "\\r"}.get(c, "\\u%04x" % c))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _c14n_value(v: Any, where: str, depth: int) -> str:
    if depth > LIMITS["depth"]:
        _fail("c14n-value", where, "nesting exceeds %d levels" % LIMITS["depth"])
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if type(v) is int:
        try:
            v = float(v)
        except OverflowError:
            _fail("c14n-value", where, "non-finite number")
    if type(v) is float:
        if not math.isfinite(v):
            _fail("c14n-value", where, "non-finite number")
        return es_number(v)
    if type(v) is str:
        return _c14n_string(v, where)
    if type(v) is list:
        return "[" + ",".join(_c14n_value(x, where + "/" + str(i), depth + 1) for i, x in enumerate(v)) + "]"
    if type(v) is dict:
        if any(type(k) is not str for k in v):
            _fail("c14n-value", where, "non-string keys")
        parts = []
        for k in sorted(v, key=_utf16_key):
            p = where + "/" + _pointer(k)
            parts.append(_c14n_string(k, p) + ":" + _c14n_value(v[k], p, depth + 1))
        return "{" + ",".join(parts) + "}"
    return _fail("c14n-value", where, "not a JSON value (%s)" % type(v).__name__)


def canonical_json(value: Any) -> str:
    """`datapass-c14n/1` (RFC 8785 JCS) text. Raises EngineeringError DP-ENG-016 on a value it refuses."""
    return _c14n_value(value, "", 1)


def canonical_bytes(value: Any) -> bytes:
    return canonical_json(value).encode("utf-8")


def sha256_hex(data: bytes | str) -> str:
    return hashlib.sha256(data.encode("utf-8") if isinstance(data, str) else data).hexdigest()


def digest(value: Any) -> dict:
    return {"alg": "sha256", "over": C14N, "value": sha256_hex(canonical_bytes(value))}


def bytes_digest(data: bytes | str) -> dict:
    return {"alg": "sha256", "over": "bytes", "value": sha256_hex(data)}


def _reject_constant(name: str):
    raise ValueError("non-finite constant " + name)


def parse_json(text: str) -> Any:
    """JSON.parse equivalent: NaN/Infinity tokens are not JSON."""
    return json.loads(text, parse_constant=_reject_constant)


# ------------------------------------------------------------------------------------------------------- validation
_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:/@-]{0,159}")
_ARTIFACT_ID = re.compile(r"[a-z][a-zA-Z0-9_-]{0,79}")
_HEX64 = re.compile(r"[0-9a-f]{64}")
_COMMIT = re.compile(r"(?:[0-9a-f]{40}|[0-9a-f]{64})")
_MEDIA_TYPE = re.compile(r"[a-z0-9][a-z0-9!#$&^_.+-]{0,63}/[a-z0-9][a-z0-9!#$&^_.+-]{0,63}(?:; ?[a-z0-9-]{1,32}=[A-Za-z0-9._-]{1,64})?")
_VIEW_TOKEN = re.compile(r"[A-Za-z0-9._~-]{1,128}")
_ENDPOINT_HINT = re.compile(r"/[A-Za-z0-9._~/-]{0,255}")
_DIAG_CODE = re.compile(r"[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*")
_TIME = re.compile(r"[1-9][0-9]{3}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]{3}Z")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
_MAX_INT = 9007199254740991


def _is_number(v: Any) -> bool:
    return type(v) in (int, float)


def _is_int(v: Any) -> bool:
    return type(v) is int or (type(v) is float and v.is_integer())


def _is_one(v: Any) -> bool:
    return _is_number(v) and v == 1


def _blen(s: str) -> int:
    return len(s.encode("utf-8"))


def _inert(v: Any, where: str, depth: int) -> None:
    if depth > LIMITS["depth"]:
        _fail("engineering-envelope", where, "nesting exceeds %d levels" % LIMITS["depth"])
    if v is None or type(v) is bool:
        return
    if type(v) is int:
        try:
            float(v)
        except OverflowError:
            _fail("engineering-envelope", where, "non-finite number")
        return
    if type(v) is float:
        if not math.isfinite(v):
            _fail("engineering-envelope", where, "non-finite number")
        return
    if type(v) is str:
        if _lone_surrogate(v):
            _fail("engineering-envelope", where, "lone surrogate")
        return
    if type(v) is list:
        for i, x in enumerate(v):
            _inert(x, where + "/" + str(i), depth + 1)
        return
    if type(v) is dict and all(type(k) is str for k in v):
        for k in sorted(v, key=_utf16_key):
            p = where + "/" + _pointer(k)
            if _lone_surrogate(k):
                _fail("engineering-envelope", p, "lone surrogate in a key")
            _inert(v[k], p, depth + 1)
        return
    _fail("engineering-envelope", where, "not an inert JSON value")


def _object(v: Any, where: str, required: tuple, optional: tuple = ()) -> dict:
    if type(v) is not dict:
        _fail("field-invalid", where, "expected an object")
    allowed = set(required) | set(optional)
    for k in sorted(v, key=_utf16_key):
        if k not in allowed:
            _fail("unknown-key", where + "/" + _pointer(k), "unknown key")
    for k in required:
        if k not in v:
            _fail("missing-key", where + "/" + _pointer(k), "missing key")
    return v


def _id(v: Any, where: str, pattern: re.Pattern = _ID) -> str:
    if type(v) is not str or not pattern.fullmatch(v):
        _fail("field-invalid", where, "not a valid identifier")
    return v


def _text(v: Any, where: str, limit: int) -> str:
    if type(v) is not str or len(v) == 0 or _blen(v) > limit:
        _fail("field-invalid", where, "expected text of 1 to %d UTF-8 bytes" % limit)
    return v


def _one_of(v: Any, where: str, values: tuple) -> str:
    if type(v) is not str or v not in values:
        _fail("field-invalid", where, "expected one of " + ", ".join(values))
    return v


def _time(v: Any, where: str) -> str:
    ok = type(v) is str and _TIME.fullmatch(v) is not None
    if ok:
        try:
            parsed = datetime.strptime(v, "%Y-%m-%dT%H:%M:%S.%fZ").replace(tzinfo=timezone.utc)
            ok = parsed.strftime("%Y-%m-%dT%H:%M:%S.") + "%03d" % (parsed.microsecond // 1000) + "Z" == v
        except ValueError:
            ok = False
    if not ok:
        _fail("field-invalid", where, "expected a UTC time YYYY-MM-DDTHH:MM:SS.sssZ")
    return v


def _list(v: Any, where: str, limit: int, minimum: int = 0) -> list:
    if type(v) is not list or len(v) < minimum or len(v) > limit:
        _fail("field-invalid", where, "expected a list of %d to %d items" % (minimum, limit))
    return v


def _unique(values: list, where: str, suffix: str) -> None:
    seen = set()
    for i, x in enumerate(values):
        if x in seen:
            _fail("duplicate-id", where + "/" + str(i) + suffix, "duplicate " + json.dumps(x))
        seen.add(x)


def _id_list(v: Any, where: str, limit: int) -> list:
    items = [_id(x, where + "/" + str(i)) for i, x in enumerate(_list(v, where, limit))]
    _unique(items, where, "")
    return items


def _digest(v: Any, where: str) -> dict:
    d = _object(v, where, ("alg", "over", "value"))
    if d["alg"] != "sha256" or type(d["alg"]) is not str:
        _fail("digest", where + "/alg", "alg must be sha256")
    if type(d["over"]) is not str or d["over"] not in ("bytes", C14N):
        _fail("digest", where + "/over", "over must be bytes or " + C14N)
    if type(d["value"]) is not str or not _HEX64.fullmatch(d["value"]):
        _fail("digest", where + "/value", "value must be 64 lowercase hex characters")
    return d


def _scalar(v: Any, where: str) -> Any:
    if v is None or type(v) is bool or _is_number(v):
        return v
    if type(v) is str and _blen(v) <= 4000:
        return v
    return _fail("field-invalid", where, "expected null, a boolean, a finite number or text up to 4000 bytes")


def _type_name(v: Any) -> str:
    if v is None:
        return "null"
    if type(v) is bool:
        return "boolean"
    if _is_number(v):
        return "number"
    return "string"


def _artifact_ref(v: dict, w: str) -> None:
    _object(v, w, ("format", "version", "kind", "id", "sha256", "mediaType", "bytes", "scope"), ("locator",))
    _id(v["id"], w + "/id", _ARTIFACT_ID)
    if type(v["sha256"]) is not str or not _HEX64.fullmatch(v["sha256"]):
        _fail("digest", w + "/sha256", "sha256 must be 64 lowercase hex characters of the exact bytes")
    if type(v["mediaType"]) is not str or not _MEDIA_TYPE.fullmatch(v["mediaType"]):
        _fail("field-invalid", w + "/mediaType", "expected a lowercase media type")
    b = v["bytes"]
    if not _is_number(b) or not _is_int(b) or b < 0 or b > _MAX_INT:
        _fail("field-invalid", w + "/bytes", "expected a byte count")
    _one_of(v["scope"], w + "/scope", ("public", "private"))
    if "locator" in v:
        _text(v["locator"], w + "/locator", 1024)


def _run_receipt(v: dict) -> None:
    _object(v, "", ("format", "version", "kind", "runId", "inputDigest", "code", "model", "status", "cancelRequested",
                    "times", "checks", "coverage", "artifacts", "diagnostics"))
    _id(v["runId"], "/runId")
    _digest(v["inputDigest"], "/inputDigest")
    code = _object(v["code"], "/code", ("version",), ("commit",))
    _text(code["version"], "/code/version", 64)
    if "commit" in code and (type(code["commit"]) is not str or not _COMMIT.fullmatch(code["commit"])):
        _fail("field-invalid", "/code/commit", "expected a 40 or 64 hex commit id")
    model = _object(v["model"], "/model", ("id", "version"), ("resolved", "reason"))
    _id(model["id"], "/model/id")
    _text(model["version"], "/model/version", 128)
    if "resolved" in model and model["resolved"] is not None:
        _text(model["resolved"], "/model/resolved", 256)
    if "reason" in model:
        _text(model["reason"], "/model/reason", 400)
    status = _one_of(v["status"], "/status", RUN_STATUSES)
    if type(v["cancelRequested"]) is not bool:
        _fail("field-invalid", "/cancelRequested", "expected a boolean")
    times = _object(v["times"], "/times", ("submittedAt", "startedAt", "finishedAt"))
    submitted = _time(times["submittedAt"], "/times/submittedAt")
    started = None if times["startedAt"] is None else _time(times["startedAt"], "/times/startedAt")
    finished = None if times["finishedAt"] is None else _time(times["finishedAt"], "/times/finishedAt")
    checks = _object(v["checks"], "/checks", ("performed", "notPerformed"))
    performed = _id_list(checks["performed"], "/checks/performed", LIMITS["checks"])
    not_performed = _id_list(checks["notPerformed"], "/checks/notPerformed", LIMITS["checks"])
    coverage = _object(v["coverage"], "/coverage", ("consumed", "ignored", "fixed"))
    lists = [(k, _id_list(coverage[k], "/coverage/" + k, LIMITS["list"])) for k in ("consumed", "ignored", "fixed")]
    artifacts = _list(v["artifacts"], "/artifacts", LIMITS["artifacts"])
    for i, a in enumerate(artifacts):
        w = "/artifacts/" + str(i)
        if type(a) is not dict:
            _fail("field-invalid", w, "expected an artifact-ref record")
        if a.get("format") != FORMAT or type(a.get("format")) is not str:
            _fail("format", w + "/format", "unsupported format")
        if not _is_one(a.get("version")):
            _fail("version", w + "/version", "unsupported version")
        if a.get("kind") != "artifact-ref" or type(a.get("kind")) is not str:
            _fail("field-invalid", w + "/kind", "expected an artifact-ref record")
        _artifact_ref(a, w)
    _unique([a["id"] for a in artifacts], "/artifacts", "/id")
    for i, d in enumerate(_list(v["diagnostics"], "/diagnostics", LIMITS["diagnostics"])):
        w = "/diagnostics/" + str(i)
        o = _object(d, w, ("code", "severity", "message"))
        if type(o["code"]) is not str or len(o["code"]) > 32 or not _DIAG_CODE.fullmatch(o["code"]):
            _fail("field-invalid", w + "/code", "expected an upper-case diagnostic code")
        _one_of(o["severity"], w + "/severity", ("info", "warning", "error"))
        _text(o["message"], w + "/message", 2000)
    # semantic rules, in this order
    if status == "queued" and (started is not None or finished is not None):
        _fail("run-status", "/times", "a queued run has neither started nor finished")
    if status == "running" and (started is None or finished is not None):
        _fail("run-status", "/times", "a running run has started and not finished")
    if status in ("succeeded", "failed") and (started is None or finished is None):
        _fail("run-status", "/times", "a %s run has started and finished" % status)
    if status == "cancelled" and finished is None:
        _fail("run-status", "/times", "a cancelled run has finished")
    if (started is not None and started < submitted) or (finished is not None and finished < (started or submitted)):
        _fail("run-status", "/times", "times go backwards")
    if status == "cancelled" and v["cancelRequested"] is not True:
        _fail("run-status", "/cancelRequested", "a cancelled run records cancelRequested true")
    if "resolved" in model and model["resolved"] is None and "reason" not in model:
        _fail("model-resolution", "/model/resolved", "an unresolved model needs a reason")
    if "reason" in model and not ("resolved" in model and model["resolved"] is None):
        _fail("model-resolution", "/model/reason", "a reason is only given when resolved is null")
    done = set(performed)
    for i, c in enumerate(not_performed):
        if c in done:
            _fail("disjoint-lists", "/checks/notPerformed/" + str(i), "check %s is also performed" % json.dumps(c))
    placed: set = set()
    for k, ids in lists:
        for i, p in enumerate(ids):
            if p in placed:
                _fail("disjoint-lists", "/coverage/%s/%d" % (k, i), "parameter %s is in two coverage lists" % json.dumps(p))
        placed.update(ids)


def _selection_binding(v: dict) -> None:
    _object(v, "", ("format", "version", "kind", "entityId", "geometryRevision", "viewToken", "bindings"), ("timeCursor",))
    _id(v["entityId"], "/entityId")
    _digest(v["geometryRevision"], "/geometryRevision")
    if type(v["viewToken"]) is not str or not _VIEW_TOKEN.fullmatch(v["viewToken"]):
        _fail("field-invalid", "/viewToken", "expected an opaque view token")
    bindings = []
    for i, b in enumerate(_list(v["bindings"], "/bindings", LIMITS["bindings"])):
        w = "/bindings/" + str(i)
        o = _object(b, w, ("signal", "entityId", "status"), ("source",))
        _id(o["signal"], w + "/signal")
        if o["entityId"] is not None:
            _id(o["entityId"], w + "/entityId")
        _one_of(o["status"], w + "/status", BINDING_STATUSES)
        if "source" in o:
            _text(o["source"], w + "/source", 400)
        bindings.append(o)
    if "timeCursor" in v and (not _is_number(v["timeCursor"]) or v["timeCursor"] < 0):
        _fail("field-invalid", "/timeCursor", "expected seconds >= 0")
    _unique([b["signal"] for b in bindings], "/bindings", "/signal")
    for i, b in enumerate(bindings):
        w = "/bindings/" + str(i)
        if b["status"] == "unmapped" and (b["entityId"] is not None or "source" in b):
            _fail("binding-status", w, "an unmapped signal has no entity and no source")
        if b["status"] == "sourced" and (b["entityId"] is None or "source" not in b):
            _fail("binding-status", w, "a sourced binding names its entity and its source")
        if b["status"] == "inferred" and b["entityId"] is None:
            _fail("binding-status", w, "an inferred binding names its entity")


def _approval_request(v: dict) -> None:
    for k in sorted(v, key=_utf16_key):
        if k in APPROVAL_STATE_KEYS:
            _fail("approval-state", "/" + _pointer(k), "an approval request carries no approval state")
    _object(v, "", ("format", "version", "kind", "purpose", "baseRevision", "proposalDigest", "requester", "endpointHint",
                    "presentationOnly"))
    _text(v["purpose"], "/purpose", 400)
    _digest(v["baseRevision"], "/baseRevision")
    _digest(v["proposalDigest"], "/proposalDigest")
    _id(v["requester"], "/requester")
    hint = v["endpointHint"]
    if (type(hint) is not str or not _ENDPOINT_HINT.fullmatch(hint) or "//" in hint
            or any(s in ("..", ".") for s in hint.split("/"))):
        _fail("field-invalid", "/endpointHint", "expected an absolute path without host, query or dot segments")
    if v["presentationOnly"] is not True:
        _fail("approval-state", "/presentationOnly", "presentationOnly must be true")


def _parameter_diff(v: dict) -> None:
    _object(v, "", ("format", "version", "kind", "baseRevision", "changes"))
    _digest(v["baseRevision"], "/baseRevision")
    changes = []
    for i, c in enumerate(_list(v["changes"], "/changes", LIMITS["list"], 1)):
        w = "/changes/" + str(i)
        o = _object(c, w, ("id", "unit", "from", "to", "consumedBy"))
        _id(o["id"], w + "/id")
        u = o["unit"]
        if type(u) is not str or _blen(u) > 32 or _CONTROL.search(u):
            _fail("field-invalid", w + "/unit", 'expected a unit string ("" when dimensionless)')
        _scalar(o["from"], w + "/from")
        _scalar(o["to"], w + "/to")
        _id_list(o["consumedBy"], w + "/consumedBy", LIMITS["consumedBy"])
        changes.append(o)
    _unique([c["id"] for c in changes], "/changes", "/id")
    for i, c in enumerate(changes):
        a, b, w = c["from"], c["to"], "/changes/" + str(i)
        if (a is None and b is None) or canonical_json(a) == canonical_json(b):
            _fail("diff-change", w, "the change does not change the value")
        if a is not None and b is not None and _type_name(a) != _type_name(b):
            _fail("diff-change", w, "the change switches the value type")


def validate(record: Any) -> dict:
    """Validate one parsed record; raises EngineeringError with a stable code on the first refusal."""
    if type(record) is not dict:
        _fail("engineering-envelope", "", "expected one JSON object")
    _inert(record, "", 1)
    if record.get("format") != FORMAT or type(record.get("format")) is not str:
        _fail("format", "/format", "unsupported format")
    if not _is_one(record.get("version")):
        _fail("version", "/version", "unsupported version")
    kind = record.get("kind")
    if type(kind) is not str or kind not in KINDS:
        _fail("kind", "/kind", "unknown kind")
    {"artifact-ref": lambda r: _artifact_ref(r, ""), "run-receipt": _run_receipt, "selection-binding": _selection_binding,
     "approval-request": _approval_request, "parameter-diff": _parameter_diff}[kind](record)
    return record


def decide(text: str) -> dict:
    """Decide one record given as JSON text. Never raises for a refused record."""
    try:
        if type(text) is not str or _blen_safe(text) > LIMITS["textBytes"]:
            _fail("engineering-envelope", "", "the record exceeds %d bytes" % LIMITS["textBytes"])
        try:
            value = parse_json(text)
        except (ValueError, RecursionError):
            return _refusal(EngineeringError("engineering-envelope", "", "not JSON"))
        record = validate(value)
        return {"ok": True, "kind": record["kind"], "digest": digest(record)}
    except EngineeringError as error:
        return _refusal(error)


def _blen_safe(text: str) -> int:
    return len(text.encode("utf-8", "surrogatepass"))


def _refusal(error: EngineeringError) -> dict:
    return {"ok": False, "code": error.code, "rule": error.rule, "gate": error.gate, "where": error.where,
            "message": str(error)}


def main(argv: list) -> int:
    if len(argv) >= 2 and argv[0] == "validate":
        refused = False
        for name in argv[1:]:
            with open(name, "rb") as handle:
                got = decide(handle.read().decode("utf-8"))
            refused = refused or not got["ok"]
            print(json.dumps(got, ensure_ascii=False, sort_keys=True))
        return 1 if refused else 0
    if len(argv) == 2 and argv[0] == "c14n":
        with open(argv[1], "rb") as handle:
            sys.stdout.buffer.write(canonical_bytes(parse_json(handle.read().decode("utf-8"))))
        return 0
    print(__doc__.split("Command line:")[1], file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

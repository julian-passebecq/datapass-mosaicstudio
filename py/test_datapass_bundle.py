"""py/datapass_bundle.py decides the datapass.bundle v1 corpus exactly like the TypeScript validator.

tests/fixtures/bundle/manifest.json (generated by scripts/make-bundle-corpus.mjs, all SYNTHETIC) pins, for every
fixture, the accept/reject decision, the stable DP-BUN code, the refused file and, for accepted bundles, the file
hashes and the bundle identity. tests/bundle.test.mjs asserts the same manifest for TypeScript.
"""
import hashlib
import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "py"))
import datapass_bundle as db  # noqa: E402

CORPUS = ROOT / "tests" / "fixtures" / "bundle"
MANIFEST = json.loads((CORPUS / "manifest.json").read_text(encoding="utf-8"))
CONTRACT = json.loads((ROOT / "docs" / "contracts" / "diagnostic-codes.json").read_text(encoding="utf-8"))


def _text(name: str) -> str:
    return (CORPUS / name).read_bytes().decode("utf-8")


class BundleCodeTableTests(unittest.TestCase):
    def test_python_table_matches_the_contract(self):
        expected = {row["rule"]: (row["code"], row["gate"]) for row in CONTRACT["codes"]
                    if row["code"].startswith("DP-BUN-") and "py" in row["languages"]}
        self.assertEqual(db.BUNDLE_CODES, expected)


class BundleCorpusTests(unittest.TestCase):
    def test_every_fixture_matches_the_manifest(self):
        for fixture in MANIFEST["fixtures"]:
            with self.subTest(fixture["file"]):
                got = db.decide(_text(fixture["file"]))
                if fixture["expect"] == "accept":
                    self.assertTrue(got["ok"], got)
                    self.assertEqual(got["bundleSha256"], fixture["bundleSha256"])
                    self.assertEqual(got["files"], fixture["files"])
                else:
                    self.assertFalse(got["ok"])
                    self.assertEqual((got["code"], got["where"], got.get("artifactCode")),
                                     (fixture["code"], fixture["where"], fixture.get("artifactCode")), got["message"])

    def test_hashes_are_over_the_exact_embedded_text(self):
        doc = json.loads(_text("valid/exact-bytes.json"))
        for f in doc["files"]:
            self.assertEqual(f["sha256"], hashlib.sha256(f["text"].encode("utf-8")).hexdigest())
        sums = next(f for f in doc["files"] if f["path"] == "SHA256SUMS")
        self.assertEqual(db.validate(doc)["bundleSha256"], hashlib.sha256(sums["text"].encode("utf-8")).hexdigest())

    def test_secret_keys(self):
        for key in ("token", "runtimeToken", "DATAPASS_RUNTIME_TOKEN", "apiKey", "api-key", "Authorization", "password"):
            self.assertTrue(db.is_secret_key(key), key)
        for key in ("tokenCount", "tokens", "priceChangePct", "secretary", "token\n"):
            self.assertFalse(db.is_secret_key(key), key)

    def test_cli_validate(self):
        valid = str(CORPUS / "valid" / "one-run.json")
        invalid = str(CORPUS / "invalid" / "h-file-hash.json")
        ok = subprocess.run([sys.executable, "-I", str(ROOT / "py" / "datapass_bundle.py"), "validate", valid],
                            capture_output=True, text=True, encoding="utf-8")
        self.assertEqual(ok.returncode, 0, ok.stderr)
        self.assertTrue(json.loads(ok.stdout)["ok"])
        bad = subprocess.run([sys.executable, "-I", str(ROOT / "py" / "datapass_bundle.py"), "validate", valid, invalid],
                             capture_output=True, text=True, encoding="utf-8")
        self.assertEqual(bad.returncode, 1)
        lines = [json.loads(line) for line in bad.stdout.strip().splitlines()]
        self.assertEqual([line["ok"] for line in lines], [True, False])
        self.assertEqual(lines[1]["code"], "DP-BUN-003")


if __name__ == "__main__":
    unittest.main()

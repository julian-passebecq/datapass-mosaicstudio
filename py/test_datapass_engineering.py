"""py/datapass_engineering.py decides the datapass.engineering/1 corpus exactly like the TypeScript validator.

tests/fixtures/engineering/manifest.json (generated by scripts/make-engineering-corpus.mjs, all SYNTHETIC except the
byte-exact 0.8.1 artifact) pins, for every record, the decision, the stable DP-ENG code and the refused location, and for
every datapass-c14n/1 vector the canonical bytes or the refusal. tests/engineering.test.mjs asserts the same manifest
for TypeScript.
"""
import hashlib
import json
import subprocess
import sys
import unittest
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "py"))
import datapass_artifact as da  # noqa: E402
import datapass_engineering as de  # noqa: E402

CORPUS = ROOT / "tests" / "fixtures" / "engineering"
MANIFEST = json.loads((CORPUS / "manifest.json").read_text(encoding="utf-8"))
CONTRACT = json.loads((ROOT / "docs" / "contracts" / "diagnostic-codes.json").read_text(encoding="utf-8"))


def _text(name: str) -> str:
    return (CORPUS / name).read_bytes().decode("utf-8")


def _special(name: str):
    return {"NaN": float("nan"), "Infinity": float("inf"), "-Infinity": float("-inf"), "undefined": {"u": object()},
            "function": lambda: 1, "date": datetime(2026, 1, 1)}[name]


class EngineeringCodeTableTests(unittest.TestCase):
    def test_python_table_matches_the_contract(self):
        expected = {row["rule"]: (row["code"], row["gate"]) for row in CONTRACT["codes"] if row["code"].startswith("DP-ENG-")}
        self.assertEqual(de.ENGINEERING_CODES, expected)

    def test_every_code_has_a_fixture_or_vector(self):
        covered = {f["code"] for f in MANIFEST["fixtures"] if f["expect"] == "reject"}
        covered |= {v["code"] for v in MANIFEST["vectors"] if v["expect"] == "reject"}
        self.assertEqual(covered, {code for code, _ in de.ENGINEERING_CODES.values()})


class EngineeringCorpusTests(unittest.TestCase):
    def test_corpus_size(self):
        self.assertGreaterEqual(sum(f["expect"] == "accept" for f in MANIFEST["fixtures"]), 8)
        self.assertGreaterEqual(sum(f["expect"] == "reject" for f in MANIFEST["fixtures"]), 20)
        self.assertEqual({f["kind"] for f in MANIFEST["fixtures"] if f["expect"] == "accept"}, set(de.KINDS))

    def test_every_record_matches_the_manifest(self):
        for fixture in MANIFEST["fixtures"]:
            with self.subTest(fixture["file"]):
                got = de.decide(_text(fixture["file"]))
                if fixture["expect"] == "accept":
                    self.assertTrue(got["ok"], got)
                    self.assertEqual((got["kind"], got["digest"]["value"]), (fixture["kind"], fixture["digest"]))
                else:
                    self.assertFalse(got["ok"])
                    self.assertEqual((got["code"], got["where"]), (fixture["code"], fixture["where"]), got["message"])

    def test_every_c14n_vector(self):
        for vector in MANIFEST["vectors"]:
            with self.subTest(vector["id"]):
                if vector["expect"] == "canonical":
                    expected = (CORPUS / vector["canonical"]).read_bytes()
                    got = de.canonical_bytes(de.parse_json(_text(vector["input"])))
                    self.assertEqual(got, expected)
                    self.assertEqual(hashlib.sha256(got).hexdigest(), vector["sha256"])
                    continue
                value = de.parse_json(_text(vector["input"])) if "input" in vector else {"x": [1, _special(vector["special"])]}
                with self.assertRaises(de.EngineeringError) as caught:
                    de.canonical_json(value)
                self.assertEqual((caught.exception.code, caught.exception.where), (vector["code"], vector["where"]))

    def test_proposal_digest_is_the_c14n_digest_of_the_diff(self):
        diff = de.parse_json(_text("valid/parameter-diff.json"))
        approval = de.parse_json(_text("valid/approval-request.json"))
        self.assertEqual(approval["proposalDigest"], de.digest(diff))

    def test_legacy_artifact_is_referenced_by_exact_bytes_and_still_valid(self):
        legacy = MANIFEST["legacy"]
        data = (CORPUS / legacy["file"]).read_bytes()
        self.assertEqual((hashlib.sha256(data).hexdigest(), len(data)), (legacy["sha256"], legacy["bytes"]))
        ref = de.validate(de.parse_json(_text(legacy["referencedBy"])))
        self.assertEqual((ref["sha256"], ref["bytes"]), (legacy["sha256"], legacy["bytes"]))
        self.assertEqual(de.bytes_digest(data)["value"], ref["sha256"])
        self.assertTrue(da.decide(json.loads(data.decode("utf-8")))["ok"])


class CanonicalJsonTests(unittest.TestCase):
    def test_es_number_formatting(self):
        cases = {1.0: "1", -0.0: "0", 1e21: "1e+21", 1e20: "100000000000000000000", 1e-7: "1e-7", 1e-6: "0.000001",
                 0.1: "0.1", 5e-324: "5e-324", 1.5e300: "1.5e+300", 123.456: "123.456", -2.5e-8: "-2.5e-8",
                 2 ** 53 + 1: "9007199254740992", 100: "100"}
        for value, text in cases.items():
            with self.subTest(value):
                self.assertEqual(de.canonical_json(value), text)

    def test_non_plain_values_are_refused(self):
        for value in ((1, 2), {1: "a"}, {"a": {1, 2}}, b"x", float("nan")):
            with self.subTest(repr(value)):
                with self.assertRaises(de.EngineeringError) as caught:
                    de.canonical_json(value)
                self.assertEqual(caught.exception.code, "DP-ENG-016")

    def test_bool_is_not_a_number(self):
        self.assertEqual(de.canonical_json([True, False, 1, 0]), "[true,false,1,0]")

    def test_cli(self):
        valid = str(CORPUS / "valid" / "parameter-diff.json")
        invalid = str(CORPUS / "invalid" / "a-approval-status.json")
        run = subprocess.run([sys.executable, "-I", str(ROOT / "py" / "datapass_engineering.py"), "validate", valid, invalid],
                             capture_output=True, text=True, encoding="utf-8")
        self.assertEqual(run.returncode, 1, run.stderr)
        lines = [json.loads(line) for line in run.stdout.strip().splitlines()]
        self.assertEqual([line["ok"] for line in lines], [True, False])
        self.assertEqual(lines[1]["code"], "DP-ENG-014")
        out = subprocess.run([sys.executable, "-I", str(ROOT / "py" / "datapass_engineering.py"), "c14n",
                              str(CORPUS / "c14n" / "rfc8785-sample.json")], capture_output=True)
        self.assertEqual(out.returncode, 0)
        self.assertEqual(out.stdout, (CORPUS / "c14n" / "rfc8785-sample.c14n").read_bytes())


if __name__ == "__main__":
    unittest.main()
